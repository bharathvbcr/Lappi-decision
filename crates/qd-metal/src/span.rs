//! The span pointer head, served: load `span_head.safetensors` from a release, map a context's
//! lines to token positions, and score `line_count + 1` rows from the tower's hidden states.
//!
//! Everything here is host-side and runs without a GPU. The GPU work is reading the tower's
//! residual stream at the rows this module names ([`crate::model::Model::final_hidden`]).
//!
//! # The head is the one `qd_train.heads.SpanPointerHead` trains
//!
//! ```text
//! q_start = start_proj . h[query]          q_end = end_proj . h[query]       (bias-free, [H, H])
//! start[j] = q_start . h[candidate j]      end[j] = q_end . h[candidate j]   j = 0 .. n - 1
//! start[n] = q_start . abstain_start       end[n] = q_end . abstain_end      the abstain row is LAST
//! ```
//!
//! `n` rows plus one is exactly `qd_runtime::answer::span_rows` (`line_count + RESERVED_NOUL_ROWS`),
//! so the runtime's `validate_logits` accepts every decode. Parity with the Python head is held by
//! `tests/fixtures/span/head_scores.json`, generated by `tools/gen_span_fixture.py`.
//!
//! # The convention, which is what a wrong head would silently break
//!
//! * **Hidden state.** The tower's `last_hidden_state`, which for `Qwen3_5TextModel` is the output
//!   of the final norm, in the tower's dtype (bf16): `x * rsqrt(mean(x^2) + eps) * (1 + w)`,
//!   rounded to bf16 ([`final_hidden_row`]). `QwenDecisionStep` feeds exactly that to the head
//!   (`backbone.py`, `span_head.loss(hidden[rows].float(), plan)`). A head that read the residual
//!   stream before the norm would score differently by orders of magnitude; the tiny-tower GPU
//!   test (`tests/gpu_span.rs`) checks both that this convention matches Python and that the other
//!   one does not.
//! * **Query.** The last token of prefix + slot suffix, i.e. the position the letters are read from
//!   (`shards.training_texts`: `target_index = lengths - 2`, the last token of `<|qd_answer|>`).
//! * **Candidates.** One per context line, in line order. A line's token is the **first token whose
//!   byte span contains the line's first byte** (`shards._token_indices_for_chars`, in characters
//!   there; the tokenizer's offsets are bytes here, and a line start is the same position either
//!   way). A line start in no token is refused, as is a token holding the start of two lines: the
//!   `refuse-any` collapse policy, the only one a gate shard set is written under. A model trained
//!   under `refuse-gold` shares a candidate between collapsed lines (`GAP-G9A-RUNTIME-SPAN-
//!   CANDIDATES-MUST-SHARE-COLLAPSED-TOKENS`); this loader does not serve that head until that
//!   rule is implemented and tested against it, and says so in the refusal.
//!
//! # Which head is served
//!
//! A release records where its head came from (`release_manifest.json`'s `span_head.source`, which
//! `qd-export` copies from `tools/ckpt_average.py`'s `span_head_source`). [`open`] serves:
//!
//! * a head of `mode: "seed"`: one named seed's head, never a blend;
//! * a head of `mode: "averaged"` **only** with an `averaged_head_preregistration` the export read
//!   (`campaign/v6-averaging-preregistered.json`, recorded by digest): the averaged head is a
//!   pre-registered primary row or it is not served, because a weight average of independently
//!   initialised heads collapses the span (`GAP-WEIGHT-AVERAGE-COLLAPSES-THE-SPAN-HEAD-2026-10-06`);
//! * nothing else. No `span_head` block (a release exported before provenance was recorded), a
//!   source of `null`, another contract version, a hidden size that is not the tower's, or a file
//!   whose digest is not the recorded one is [`SpanServing::Refused`] with the reason, and a span
//!   slot is answered with that reason. Choice and score slots are unaffected.
//!
//! Rule 7 holds: this module scores and admits; it never emits a PASS or discharges a requirement.

use std::ops::Range;
use std::path::Path;

use qd_export::export::{KNOWN_AVERAGED_PREREGISTRATIONS, SPAN_CONTRACT_VERSION};
use qd_runtime::Context;
use qd_runtime::release::{MANIFEST_FILE, SPAN_HEAD_FILE};
use qd_runtime::render::{M_CTX_BEGIN, M_CTX_END};
use serde_json::Value;

use crate::error::{MetalError, Result};
use crate::safetensors::{Dtype, SafeTensors};

/// The head's four tensors, as `SpanPointerHead.state_dict()` names them (the names the export
/// writes into `span_head.safetensors`).
const START_PROJ: &str = "start_proj.weight";
const END_PROJ: &str = "end_proj.weight";
const ABSTAIN_START: &str = "abstain_start";
const ABSTAIN_END: &str = "abstain_end";

/// The span head's weights, all f32.
#[derive(Debug, Clone, PartialEq)]
pub struct SpanHead {
    hidden: usize,
    start_proj: Vec<f32>,
    end_proj: Vec<f32>,
    abstain_start: Vec<f32>,
    abstain_end: Vec<f32>,
    /// SHA-256 of `span_head.safetensors`, the digest the release manifest records.
    file_sha256: [u8; 32],
}

/// Start and end scores for one span slot: `n_candidates + 1` rows each, abstain last.
#[derive(Debug, Clone, PartialEq)]
pub struct SpanScores {
    pub start: Vec<f32>,
    pub end: Vec<f32>,
}

fn refuse(msg: impl Into<String>) -> MetalError {
    MetalError::Weights(format!("span head: {}", msg.into()))
}

impl SpanHead {
    /// Read `path` for a tower of `hidden` width: exactly the four tensors, each F32 at its shape,
    /// every value finite.
    pub fn load(path: &Path, hidden: usize) -> Result<Self> {
        let st = SafeTensors::open(path)?;
        let want = [
            (ABSTAIN_END, vec![hidden]),
            (ABSTAIN_START, vec![hidden]),
            (END_PROJ, vec![hidden, hidden]),
            (START_PROJ, vec![hidden, hidden]),
        ];
        let names: Vec<&str> = st.names().collect();
        let expected: Vec<&str> = want.iter().map(|(n, _)| *n).collect();
        if names != expected {
            return Err(refuse(format!(
                "{} holds {names:?}, not exactly {expected:?}",
                path.display()
            )));
        }
        let take = |name: &str, shape: &[usize]| -> Result<Vec<f32>> {
            st.expect(name, shape, &[Dtype::F32])?;
            let values = st.f32(name, shape)?;
            if let Some(i) = values.iter().position(|v| !v.is_finite()) {
                return Err(refuse(format!("{name}[{i}] is {}", values[i])));
            }
            Ok(values)
        };
        let abstain_end = take(ABSTAIN_END, &[hidden])?;
        let abstain_start = take(ABSTAIN_START, &[hidden])?;
        let end_proj = take(END_PROJ, &[hidden, hidden])?;
        let start_proj = take(START_PROJ, &[hidden, hidden])?;
        let bytes = std::fs::read(path).map_err(|e| refuse(format!("{}: {e}", path.display())))?;
        Ok(Self {
            hidden,
            start_proj,
            end_proj,
            abstain_start,
            abstain_end,
            file_sha256: qd_runtime::sha256(&bytes),
        })
    }

    pub fn hidden(&self) -> usize {
        self.hidden
    }

    /// SHA-256 of the head's file.
    pub fn file_sha256(&self) -> [u8; 32] {
        self.file_sha256
    }

    /// Score `n` candidates (`candidates` is `[n, hidden]` row-major) against `query`, for both
    /// pointers. `n` may be 0: the abstain row alone, which is what the runtime asks of a context
    /// with no lines.
    ///
    /// The projection and every dot are accumulated in f64 and rounded to f32 once, so the result
    /// is within f32 rounding of the exact value, as torch's f32 matmul is (they need not agree in
    /// the last bits; `head_scores.json` holds them to 2e-5 of the largest score).
    pub fn scores(&self, candidates: &[f32], n: usize, query: &[f32]) -> Result<SpanScores> {
        let h = self.hidden;
        if query.len() != h {
            return Err(MetalError::Input(format!(
                "the query hidden state has {} values, not {h}",
                query.len()
            )));
        }
        if n.checked_mul(h) != Some(candidates.len()) {
            return Err(MetalError::Input(format!(
                "{} candidate values for {n} candidates of width {h}",
                candidates.len()
            )));
        }
        let point = |proj: &[f32], abstain: &[f32]| -> Result<Vec<f32>> {
            // nn.Linear without bias: q[i] = sum_j W[i][j] * x[j], an f32 tensor.
            let q: Vec<f32> = proj
                .chunks_exact(h)
                .map(|row| dot(row, query) as f32)
                .collect();
            let mut out: Vec<f32> = candidates
                .chunks_exact(h)
                .map(|c| dot(&q, c) as f32)
                .collect();
            out.push(dot(&q, abstain) as f32);
            if let Some(i) = out.iter().position(|v| !v.is_finite()) {
                return Err(MetalError::Input(format!("span score {i} is {}", out[i])));
            }
            Ok(out)
        };
        Ok(SpanScores {
            start: point(&self.start_proj, &self.abstain_start)?,
            end: point(&self.end_proj, &self.abstain_end)?,
        })
    }
}

fn dot(a: &[f32], b: &[f32]) -> f64 {
    a.iter()
        .zip(b)
        .map(|(x, y)| f64::from(*x) * f64::from(*y))
        .sum()
}

/// Round to bf16 (nearest, ties to even) and widen back: what a bf16 tower hands the head.
pub fn round_bf16(v: f32) -> f32 {
    tessl::tensor::bf16_bits_to_f32(tessl::tensor::f32_to_bf16_bits(v))
}

/// The tower's `last_hidden_state` row for one residual row: the final norm, then bf16.
///
/// `Qwen3_5RMSNorm` is zero-centred: `x * rsqrt(mean(x^2) + eps) * (1 + w)`, computed in f32 and
/// cast back to the tower's dtype. `norm_w` is the checkpoint's `w`, not `1 + w`.
pub fn final_hidden_row(resid: &[f32], norm_w: &[f32], eps: f32) -> Vec<f32> {
    let mean_sq = resid
        .iter()
        .map(|x| f64::from(*x) * f64::from(*x))
        .sum::<f64>()
        / resid.len() as f64;
    let inv = (1.0 / (mean_sq + f64::from(eps)).sqrt()) as f32;
    resid
        .iter()
        .zip(norm_w)
        .map(|(x, w)| round_bf16(x * inv * (1.0 + w)))
        .collect()
}

/// The byte range of the escaped context inside a rendered prefix, as
/// `RenderedPrompt.context_region` (Python) and `RenderedPrompt::context_region` (Rust) find it:
/// after the first `<|qd_context_begin|>\n`, before the last `\n<|qd_context_end|>`.
pub fn context_region(prefix: &str) -> Result<Range<usize>> {
    let begin = format!("{M_CTX_BEGIN}\n");
    let end = format!("\n{M_CTX_END}");
    let start = prefix
        .find(&begin)
        .map(|i| i + begin.len())
        .ok_or_else(|| {
            MetalError::Input("the prefix has no context region (no context-begin marker)".into())
        })?;
    let stop = prefix
        .rfind(&end)
        .filter(|stop| *stop >= start)
        .ok_or_else(|| {
            MetalError::Input("the prefix has no context region (no context-end marker)".into())
        })?;
    Ok(start..stop)
}

/// Byte offsets of every line start of `region`, in `prefix`'s coordinates: the runtime's own
/// line rule (`Context::line_starts`: `\n` terminates a line, a trailing `\n` opens no empty last
/// line, CR is content, an empty context has none).
pub fn line_starts_in(prefix: &str, region: &Range<usize>) -> Vec<usize> {
    let ctx = Context::from_bytes(prefix.as_bytes()[region.clone()].to_vec());
    if ctx.line_count() == 0 {
        return Vec::new();
    }
    ctx.line_starts()
        .into_iter()
        .map(|s| region.start + s)
        .collect()
}

/// For each line start, the index of the first token whose byte span `[s, e)` contains it.
///
/// `offsets` is the tokenizer's `(start, end)` per token; special tokens carry `(0, 0)` and
/// byte-level BPE can give several tokens one span, so nothing assumes the spans are sorted. A
/// line start in no token is refused (a neighbour is never substituted: a pointer at the wrong
/// token cites the wrong evidence), and so are two line starts in one token (`refuse-any`). Every
/// offset must lie inside the text and run forward.
pub fn candidate_tokens(
    line_starts: &[usize],
    offsets: &[(usize, usize)],
    text_len: usize,
) -> Result<Vec<usize>> {
    if line_starts.windows(2).any(|w| w[0] >= w[1]) {
        return Err(MetalError::Input(
            "line starts are not strictly ascending".into(),
        ));
    }
    if let Some((i, (s, e))) = offsets
        .iter()
        .enumerate()
        .find(|(_, (s, e))| s > e || *e > text_len)
    {
        return Err(MetalError::Input(format!(
            "token {i} has offsets ({s}, {e}) in a {text_len}-byte text: the offsets do not describe \
             this text"
        )));
    }
    let mut found: Vec<Option<usize>> = vec![None; line_starts.len()];
    for (token, (s, e)) in offsets.iter().enumerate() {
        if s == e {
            continue;
        }
        // Line starts in [s, e): the lines whose first byte this token holds.
        let lo = line_starts.partition_point(|c| c < s);
        let hi = line_starts.partition_point(|c| c < e);
        for slot in &mut found[lo..hi] {
            slot.get_or_insert(token);
        }
    }
    let mut tokens = Vec::with_capacity(found.len());
    for (line, token) in found.iter().enumerate() {
        let token = token.ok_or_else(|| {
            MetalError::Input(format!(
                "line {} starts at byte {}, which lies in no token's offset span; refused rather \
                 than mapped to a neighbouring token",
                line + 1,
                line_starts[line]
            ))
        })?;
        if let Some(prev) = tokens.iter().position(|t| *t == token) {
            return Err(MetalError::Input(format!(
                "lines {} and {} both start inside token {token}, so the pointer head cannot tell them \
                 apart (span_collapse_policy refuse-any); a head trained under refuse-gold is not served",
                prev + 1,
                line + 1
            )));
        }
        tokens.push(token);
    }
    Ok(tokens)
}

/// The token position of every context line of a rendered prefix, from the tokenizer's offsets
/// for that prefix.
pub fn plan_candidates(prefix: &str, offsets: &[(usize, usize)]) -> Result<Vec<usize>> {
    let region = context_region(prefix)?;
    candidate_tokens(&line_starts_in(prefix, &region), offsets, prefix.len())
}

/// The span head's inputs for one prefilled prefix: the token position of every context line (in
/// line order) and the tower's final-norm hidden state at them, `[tokens.len(), hidden]`.
#[derive(Debug, Clone, PartialEq)]
pub struct SpanCandidates {
    pub tokens: Vec<usize>,
    pub hidden: Vec<f32>,
}

/// What a prefill kept for the span head.
#[derive(Debug, Clone, PartialEq)]
pub enum SpanPrefix {
    /// No head is served, so nothing was kept.
    NotComputed,
    /// The context's lines could not be mapped to tokens; span queries answer with this reason.
    Refused(String),
    Ready(SpanCandidates),
}

/// What `open` decided about a release's span head.
#[derive(Debug)]
pub enum SpanServing {
    /// The directory carries no span head (a base snapshot, or a release with no
    /// `span_head.safetensors`): the base weights have no pointer head.
    Absent,
    /// A head is there and is not served, for this reason. Span slots answer with it.
    Refused(String),
    Ready(SpanHead),
}

/// A manifest string `a/b/c` as a JSON pointer.
fn at<'a>(v: &'a Value, path: &str) -> Option<&'a Value> {
    v.pointer(path)
}

fn is_hex64(s: &str) -> bool {
    s.len() == 64 && s.bytes().all(|b| b.is_ascii_hexdigit())
}

/// An averaged head is served only as the pre-registered primary row, bound by content: the
/// recorded pre-registration is one of `qd_export`'s committed `(name, sha256)` pairs (the campaign
/// file's digest, not any 64-hex string), and the export recorded from the ft ledger that every
/// input seed shared one span-head init, so the average is of heads that grew from the same point
/// and not the near-orthogonal blend that collapsed v5's span.
fn check_averaged(block: &Value) -> std::result::Result<(), String> {
    let not_registered = || {
        "the span head is a weight average of the seeds' heads, and the manifest does not say it was \
         pre-registered as the primary row against the committed campaign/v6-averaging-preregistered.json \
         (averaged_head_preregistration must be that file's name and sha256): the blend is not served. \
         Export from a --span-head-seed checkpoint, or with --averaged-head-preregistration and --ft-ledger"
            .to_string()
    };
    let prereg = block
        .get("averaged_head_preregistration")
        .filter(|p| p.is_object())
        .ok_or_else(not_registered)?;
    let (name, sha) = (
        prereg.get("name").and_then(Value::as_str),
        prereg.get("sha256").and_then(Value::as_str),
    );
    let known = KNOWN_AVERAGED_PREREGISTRATIONS
        .iter()
        .any(|(n, d)| Some(*n) == name && Some(*d) == sha);
    if prereg.get("row").and_then(Value::as_str) != Some("primary") || !known {
        return Err(not_registered());
    }
    let init = block.get("shared_init").filter(|i| i.is_object());
    let seeds = init.and_then(|i| i.get("seeds")).and_then(Value::as_array);
    let rows = init
        .and_then(|i| i.get("ft_row_ids"))
        .and_then(Value::as_array);
    let distinct = seeds.is_some_and(|s| {
        let mut v: Vec<u64> = s.iter().filter_map(Value::as_u64).collect();
        let n = v.len();
        v.sort_unstable();
        v.dedup();
        n == s.len() && v.len() == n
    });
    let ok = init.is_some_and(|i| {
        i.get("shared").and_then(Value::as_bool) == Some(true)
            && i.get("content_digest")
                .and_then(Value::as_str)
                .is_some_and(|d| !d.trim().is_empty() && d.bytes().all(|b| b.is_ascii_hexdigit()))
    }) && distinct
        && seeds.is_some_and(|s| s.len() >= 2)
        && seeds.map(Vec::len) == rows.map(Vec::len);
    if ok {
        Ok(())
    } else {
        Err("the manifest carries no verified evidence that every seed's span head grew from one shared init \
             (span_head.shared_init: shared true, one content_digest, 2 or more distinct seeds, one ft row each; \
             the export reads it from the ft ledger with --ft-ledger): a v5-style average of independently \
             initialised heads is the blend that collapsed the span and is not served"
            .to_string())
    }
}

/// Decide whether the release in `dir` serves a span head, for a tower of `hidden` width.
pub fn open(dir: &Path, hidden: usize) -> SpanServing {
    let head_path = dir.join(SPAN_HEAD_FILE);
    if !head_path.is_file() {
        // A manifest that names a span head whose file is gone is not a release with no head.
        let names_head = std::fs::read_to_string(dir.join(MANIFEST_FILE))
            .ok()
            .and_then(|t| serde_json::from_str::<Value>(&t).ok())
            .is_some_and(|m| m.get("span_head").is_some_and(|b| !b.is_null()));
        return if names_head {
            SpanServing::Refused(format!(
                "the release manifest records a span_head block but {SPAN_HEAD_FILE} is missing from {}",
                dir.display()
            ))
        } else {
            SpanServing::Absent
        };
    }
    match open_checked(dir, &head_path, hidden) {
        Ok(head) => SpanServing::Ready(head),
        Err(reason) => SpanServing::Refused(reason),
    }
}

fn open_checked(
    dir: &Path,
    head_path: &Path,
    hidden: usize,
) -> std::result::Result<SpanHead, String> {
    let manifest_path = dir.join(MANIFEST_FILE);
    let text = std::fs::read_to_string(&manifest_path).map_err(|e| {
        format!(
            "{SPAN_HEAD_FILE} is present but {} cannot be read ({e}): a head with no recorded \
             provenance is not served",
            manifest_path.display()
        )
    })?;
    let manifest: Value = serde_json::from_str(&text)
        .map_err(|e| format!("{} is not JSON ({e})", manifest_path.display()))?;
    let block = manifest
        .get("span_head")
        .filter(|b| b.is_object())
        .ok_or_else(|| {
            "the release manifest has no span_head block: it was exported before the head's \
         provenance was recorded, and a head of unknown provenance may be the blend of \
         independently trained heads that collapses the span (re-export with a current \
         qd-export from a checkpoint whose manifest records span_head_source)"
                .to_string()
        })?;
    let version = block
        .pointer("/serving_contract/version")
        .and_then(Value::as_str);
    if version != Some(SPAN_CONTRACT_VERSION) {
        return Err(format!(
            "span_head.serving_contract.version is {version:?}; this loader implements {SPAN_CONTRACT_VERSION:?} \
             (final-norm hidden state, last-token query, first-token-containing candidates, abstain last)"
        ));
    }
    if block.get("file").and_then(Value::as_str) != Some(SPAN_HEAD_FILE) {
        return Err(format!("span_head.file is not {SPAN_HEAD_FILE}"));
    }
    if block.get("hidden_size").and_then(Value::as_u64) != u64::try_from(hidden).ok() {
        return Err(format!(
            "span_head.hidden_size is {}, the tower's is {hidden}",
            block
                .get("hidden_size")
                .map_or_else(|| "absent".to_string(), Value::to_string)
        ));
    }
    let bytes = std::fs::read(head_path).map_err(|e| format!("{}: {e}", head_path.display()))?;
    let actual = qd_runtime::hex(&qd_runtime::sha256(&bytes));
    let recorded_block = block.get("sha256").and_then(Value::as_str);
    let recorded_files =
        at(&manifest, &format!("/files/{SPAN_HEAD_FILE}/sha256")).and_then(Value::as_str);
    for (what, recorded) in [
        ("span_head.sha256", recorded_block),
        ("files sha256", recorded_files),
    ] {
        if recorded != Some(actual.as_str()) {
            return Err(format!(
                "{SPAN_HEAD_FILE} has sha256 {actual}, but the manifest's {what} is {recorded:?}: it is \
                 not the head that was exported"
            ));
        }
    }
    match block.pointer("/source/mode").and_then(Value::as_str) {
        Some("seed") => {
            let seed = block.pointer("/source/seed").and_then(Value::as_u64);
            let digest = block
                .pointer("/source/payload_digest")
                .and_then(Value::as_str);
            if seed.is_none() || !digest.is_some_and(is_hex64) {
                return Err(
                    "span_head.source is seed-mode but names no seed or no 64-hex payload_digest"
                        .into(),
                );
            }
        }
        Some("averaged") => check_averaged(block)?,
        other => {
            return Err(format!(
                "span_head.source.mode is {other:?}: the manifest does not say how the head was made \
                 (\"seed\" or a pre-registered \"averaged\"), so a blended head cannot be ruled out"
            ));
        }
    }
    SpanHead::load(head_path, hidden).map_err(|e| e.to_string())
}
